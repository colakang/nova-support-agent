// pnpm calibrate — pick the retrieval confidence thresholds from labelled data instead of guessing.
//
// For each labelled query (in-scope with expected doc / out-of-scope) we take the best cosine
// similarity over the whole corpus, then sweep τ:
//   τ_low  = largest τ that keeps false-accepts of out-of-scope queries ≤ MAX_FALSE_ACCEPT
//            while maximising in-scope acceptance (balanced accuracy as tie-break)
//   τ_high = smallest τ above which NO out-of-scope query scored (above it we skip the judge)
// Writes evals/results/calibration.md (committed) and prints the env lines to use.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import postgres from 'postgres';
import { loadEnv } from '@sa/shared/env';
import { openaiEmbedder, pgRetriever } from '@sa/rag';

loadEnv();
const MAX_FALSE_ACCEPT = Number(process.env.MAX_FALSE_ACCEPT ?? 0.1);
const labels = readFileSync(new URL('./retrieval_labels.jsonl', import.meta.url), 'utf8')
  .split('\n').filter(Boolean).map((l) => JSON.parse(l) as { query: string; label: 'in' | 'out'; doc_id?: string });

const sql = postgres(process.env.DATABASE_URL!, { max: 4, onnotice: () => {} });
const retriever = pgRetriever(sql, openaiEmbedder(), { high: 1, low: 0 });

type Row = { query: string; label: 'in' | 'out'; doc?: string; top: number; topDoc: string; hit5: boolean | null };
const rows: Row[] = [];
for (const l of labels) {
  const r = await retriever.search(l.query, { tier: null, k: 5 });
  const ranked = [...r.chunks].sort((a, b) => b.similarity - a.similarity);
  rows.push({
    query: l.query, label: l.label, ...(l.doc_id ? { doc: l.doc_id } : {}),
    top: r.topSimilarity, topDoc: ranked[0]?.docId ?? '-',
    hit5: l.doc_id ? r.chunks.some((c) => c.docId === l.doc_id) : null,
  });
}
await sql.end();

const ins = rows.filter((r) => r.label === 'in');
const outs = rows.filter((r) => r.label === 'out');
const pct = (n: number, d: number) => `${((100 * n) / Math.max(d, 1)).toFixed(0)}%`;

const sweep: Array<{ tau: number; tpr: number; far: number; bal: number }> = [];
for (let t = 0.2; t <= 0.8001; t += 0.01) {
  const tau = Math.round(t * 100) / 100;
  const tpr = ins.filter((r) => r.top >= tau).length / ins.length;
  const far = outs.filter((r) => r.top >= tau).length / outs.length;
  sweep.push({ tau, tpr, far, bal: (tpr + (1 - far)) / 2 });
}
const ok = sweep.filter((s) => s.far <= MAX_FALSE_ACCEPT);
const low = ok.sort((a, b) => b.tpr - a.tpr || b.bal - a.bal || a.tau - b.tau)[0] ?? sweep[0]!;
const maxOut = Math.max(...outs.map((r) => r.top));
const high = Math.max(low.tau + 0.05, Math.ceil((maxOut + 0.005) * 100) / 100);
const recall5 = ins.filter((r) => r.hit5).length;

const md: string[] = [
  '# Retrieval threshold calibration',
  '',
  `Generated by \`pnpm calibrate\` on ${new Date().toISOString().slice(0, 10)} · ${labels.length} labelled queries (${ins.length} in-scope, ${outs.length} out-of-scope) · embedding \`${process.env.EMBEDDING_MODEL ?? 'text-embedding-3-small'}\`.`,
  '',
  '| metric | value |',
  '|---|---|',
  `| recall@5 (expected doc in top 5, in-scope) | ${recall5}/${ins.length} (${pct(recall5, ins.length)}) |`,
  `| in-scope top-1 similarity (min / median) | ${Math.min(...ins.map((r) => r.top)).toFixed(3)} / ${median(ins.map((r) => r.top)).toFixed(3)} |`,
  `| out-of-scope top-1 similarity (median / max) | ${median(outs.map((r) => r.top)).toFixed(3)} / ${maxOut.toFixed(3)} |`,
  `| **τ_low** (false-accept ≤ ${MAX_FALSE_ACCEPT * 100}%) | **${low.tau.toFixed(2)}** → accepts ${pct(Math.round(low.tpr * ins.length), ins.length)} in-scope, ${pct(Math.round(low.far * outs.length), outs.length)} out-of-scope |`,
  `| **τ_high** (no out-of-scope query above) | **${high.toFixed(2)}** |`,
  '',
  'Between τ_low and τ_high an answer is only released after the grounding judge confirms every claim against the cited passages. Below τ_low passages are withheld from the model and it must decline or escalate.',
  '',
  '## Sweep',
  '',
  '| τ | in-scope accepted | out-of-scope accepted | balanced acc. |',
  '|---|---|---|---|',
  ...sweep.filter((s) => Math.round(s.tau * 100) % 5 === 0 || s.tau === low.tau || s.tau === high).map((s) => `| ${s.tau.toFixed(2)}${s.tau === low.tau ? ' ← τ_low' : ''}${s.tau === high ? ' ← τ_high' : ''} | ${(s.tpr * 100).toFixed(0)}% | ${(s.far * 100).toFixed(0)}% | ${(s.bal * 100).toFixed(0)}% |`),
  '',
  '## Per query',
  '',
  '| label | top-1 sim | top doc | expected | hit@5 | query |',
  '|---|---|---|---|---|---|',
  ...rows.sort((a, b) => (a.label === b.label ? b.top - a.top : a.label === 'in' ? -1 : 1)).map((r) => `| ${r.label} | ${r.top.toFixed(3)} | ${r.topDoc} | ${r.doc ?? ''} | ${r.hit5 === null ? '' : r.hit5 ? '✓' : '✗'} | ${r.query.replace(/\|/g, '/')} |`),
];
mkdirSync(new URL('./results/', import.meta.url), { recursive: true });
writeFileSync(new URL('./results/calibration.md', import.meta.url), md.join('\n') + '\n');
console.log(md.slice(0, 12).join('\n'));
console.log(`\nRETRIEVAL_TAU_LOW=${low.tau.toFixed(2)}\nRETRIEVAL_TAU_HIGH=${high.toFixed(2)}`);

function median(xs: number[]) { const s = [...xs].sort((a, b) => a - b); return s[Math.floor(s.length / 2)] ?? 0; }
